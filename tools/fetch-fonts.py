#!/usr/bin/env python3
"""Fetch the web fonts used by the site and write a local @font-face sheet.

The fonts are committed to the repository so that the site does not ask
Google's servers about anyone who loads it.

Run from the repository root:

    python3 tools/fetch-fonts.py
"""

import hashlib
import pathlib
import re
import urllib.request

UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0 Safari/537.36"
)

FAMILIES = [
    ("Space+Grotesk:wght@500;600;700", "Space Grotesk"),
    ("Public+Sans:ital,wght@0,400;0,500;0,600;1,400", "Public Sans"),
]

# The subsets we actually need. The rest is dead weight for a site that is
# written in English.
KEEP = ("latin", "latin-ext")

FONT_DIR = pathlib.Path("src/assets/fonts")
CSS_OUT = pathlib.Path("src/styles/fonts.css")


def fetch(url, ua=UA):
    request = urllib.request.Request(url, headers={"User-Agent": ua})
    with urllib.request.urlopen(request) as response:
        return response.read()


def main():
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)

    blocks = []
    downloaded = set()

    for spec, family in FAMILIES:
        css = fetch(
            "https://fonts.googleapis.com/css2?family=%s&display=swap" % spec
        ).decode("utf-8")

        # The sheet comes back as a series of commented subsets.
        for subset, body in re.findall(
            r"/\* ([a-z-]+) \*/\s*(@font-face \{.*?\})", css, re.S
        ):
            if subset not in KEEP:
                continue

            url = re.search(r"url\((https://[^)]+)\)", body).group(1)

            # Both families are variable fonts, so one file serves every
            # weight. Download it once and let the rules share it.
            if url not in downloaded:
                downloaded.add(url)
                # The name has to be unique per file, and the italic and
                # normal faces of a family are different files with the
                # same subset name.
                digest = hashlib.sha1(url.encode("utf-8")).hexdigest()[:8]
                name = "%s-%s-%s.woff2" % (
                    family.lower().replace(" ", "-"),
                    subset,
                    digest,
                )
                path = FONT_DIR / name
                path.write_bytes(fetch(url))
                print("fetched %s (%d bytes)" % (name, path.stat().st_size))

            blocks.append(body.replace(url, "../assets/fonts/" + name))

    header = (
        "/* Generated by tools/fetch-fonts.py. Do not edit by hand. */\n\n"
    )
    CSS_OUT.write_text(header + "\n\n".join(blocks) + "\n", encoding="utf-8")
    print("wrote %s (%d faces)" % (CSS_OUT, len(blocks)))


if __name__ == "__main__":
    main()
